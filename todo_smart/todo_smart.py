import pandas as pd
import numpy as np

df = pd.DataFrame(columns=['todo', 'priority', 'due_date'])

from google import genai
from google.colab import userdata
from pydantic import BaseModel, Field
from typing import Optional
import datetime

# Define the schema for structured output
class TodoItem(BaseModel):
    todo: str = Field(description="The description or name of the task to be done.")
    priority: str = Field(description="The priority of the task. Must be one of: 'low', 'medium', 'high'.")
    due_date: Optional[str] = Field(None, description="The due date and time of the task in ISO format or a natural language description if exact time is not clear.")

# Initialize the Gemini Client
# Make sure you have 'GOOGLE_API_KEY' set in your Colab Secrets (🔑 icon on the left)
client = genai.Client(api_key=userdata.get('GOOGLE_API_KEY'))

# Global meta list to store extracted items
meta = []

def extract_todo_to_meta(text: str):
    """
    Uses Gemini API to extract a todo, its priority, and due date from the input text,
    and appends the result to the global 'meta' list.
    """
    prompt = f"Extract the todo details from this text: '{text}'"

    response = client.models.generate_content(
        model='gemini-3.5-flash-lite',
        contents=prompt,
        config={
            'response_mime_type': 'application/json',
            'response_schema': TodoItem,
        }
    )

    # Parse response directly using Pydantic mapping
    todo_data = response.parsed
    new_todo_entry = [todo_data.todo, todo_data.priority, todo_data.due_date]
    meta.append(new_todo_entry)
    return new_todo_entry # Return the single new entry

text = input("add todo: ")
new_todo_list = extract_todo_to_meta(text) # This now gets the single extracted todo as a list

# Create a new DataFrame row from the list and concatenate
new_row_df = pd.DataFrame([new_todo_list], columns=df.columns)
df = pd.concat([df, new_row_df], ignore_index=True)

print(df)